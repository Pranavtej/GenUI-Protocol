// Generates the docs pages that must never drift from the code: the protocol spec, the component reference,
// the JSON Schemas and the benchmark. Run automatically before `dev` and `build`.
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ComponentRegistry } from "../../../packages/components/component-registry/dist/src/index.js";
import { publishedSchemas } from "../../../packages/core/schemas/dist/src/index.js";
import { TASKS, htmlSize } from "../../../packages/tooling/eval/dist/src/index.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const pages = join(root, "apps/docs/pages");
const banner = "{/* GENERATED by apps/docs/scripts/generate.mjs — edit the source, not this file. */}\n\n";
const write = (name, body) => writeFileSync(join(pages, name), banner + body);

/** MDX treats `{`, `}` and `<` in prose as code; escape them outside fences and inline code. */
const escapeMdx = (md) => {
    let fenced = false;
    return md
        .split("\n")
        .map((line) => {
            if (/^\s*```/.test(line)) {
                fenced = !fenced;
                return line;
            }
            if (fenced) return line;
            return line
                .split(/(`[^`]*`)/)
                .map((seg, i) => (i % 2 === 1 ? seg : seg.replace(/\{/g, "\\{").replace(/\}/g, "\\}").replace(/</g, "&lt;")))
                .join("");
        })
        .join("\n");
};

// ---- protocol --------------------------------------------------------------
const spec = readFileSync(join(root, "spec/SPEC.md"), "utf8")
    .replace(/^# .*\n/, "")
    .replace("](./schemas)", "](/schemas)")
    .replace("](../conformance)", "](https://github.com/Pranavtej/GenUI-Protocol/tree/main/conformance)");
write("protocol.mdx", `# Protocol specification\n\nThis page is generated from [\`spec/SPEC.md\`](https://github.com/Pranavtej/GenUI-Protocol/blob/main/spec/SPEC.md), the normative source. Machine-readable schemas are on the [Schemas](/schemas) page and test vectors live in [\`conformance/\`](https://github.com/Pranavtej/GenUI-Protocol/tree/main/conformance).\n${escapeMdx(spec)}`);

// ---- components ------------------------------------------------------------
const registry = new ComponentRegistry();
const typeOf = (d) => (d.enum ? d.enum.map((v) => JSON.stringify(v)).join(" \\| ") : d.type === "array" ? `${d.items?.type ?? "any"}[]` : d.type ?? "any");
const byCategory = {};
for (const e of registry.list()) (byCategory[e.category] ??= []).push(e);
let comp = `# Component reference\n\n${registry.list().length} built-in components, generated from the registry. Any prop may be a \`{ "$bind": "path" }\` or \`{ "$tpl": "…{{path}}…" }\` expression, and event props (\`onClick\`, …) take [actions](/protocol#11-actions).\n`;
for (const [cat, list] of Object.entries(byCategory).sort()) {
    comp += `\n## ${cat[0].toUpperCase()}${cat.slice(1)}\n`;
    for (const e of list) {
        const req = new Set(e.schema.required ?? []);
        const rows = Object.entries(e.schema.properties ?? {}).map(([k, d]) => `| \`${k}\` | \`${typeOf(d)}\` | ${req.has(k) ? "yes" : ""} |`);
        comp += `\n### \`${e.id}\`\n\n${e.description ?? ""}\n\n`;
        comp += `Renderers: ${(e.renderers ?? []).join(", ") || "—"}${e.events?.length ? ` · Events: ${e.events.map((ev) => `\`on${ev[0].toUpperCase()}${ev.slice(1)}\``).join(", ")}` : ""}\n\n`;
        comp += `| Prop | Type | Required |\n|---|---|---|\n${rows.join("\n")}\n`;
        if (e.examples?.[0]) comp += `\n\`\`\`json\n${JSON.stringify(e.examples[0], null, 2)}\n\`\`\`\n`;
    }
}
write("components.mdx", escapeMdx(comp).replace(/\\\|/g, "\\|"));

// ---- schemas ---------------------------------------------------------------
let sch = `# JSON Schemas\n\nPublished with every release in [\`spec/schemas/\`](https://github.com/Pranavtej/GenUI-Protocol/tree/main/spec/schemas) (JSON Schema draft 2020-12). \`$id\`s resolve under \`https://genui-protocol.dev/schemas/v1/\`.\n`;
for (const [file, schema] of Object.entries(publishedSchemas)) sch += `\n## \`${file}\`\n\n\`\`\`json\n${JSON.stringify(schema, null, 2)}\n\`\`\`\n`;
write("schemas.mdx", sch);

// ---- benchmark -------------------------------------------------------------
const rows = TASKS.map((t) => {
    const doc = JSON.stringify(t.reference).length;
    const html = htmlSize(t.reference);
    return { id: t.id, doc, html, ratio: html / doc };
});
const med = [...rows].map((r) => r.ratio).sort((a, b) => a - b)[Math.floor(rows.length / 2)];
write("benchmark.mdx", `# Benchmark: document size vs rendered HTML

What an LLM has to *write* matters: output tokens cost money and add latency. Here is the size of each of the ${rows.length} eval tasks' reference answer as a GenUI document, against the HTML the React renderer produces for the same document.

| Task | Document (chars) | Rendered HTML (chars) | HTML ÷ document |
|---|---|---|---|
${rows.map((r) => `| ${r.id} | ${r.doc} | ${r.html} | ${r.ratio.toFixed(1)}× |`).join("\n")}

**Median: ${med.toFixed(1)}×.** Divide characters by roughly 4 for a token estimate.

## How to read this

- **It is an upper bound.** The renderer emits inline-styled HTML, which is verbose. Hand-written HTML with utility classes would be shorter, so the true saving is smaller. The point is that a document describes *what* to show and leaves *how* to the renderer.
- **It is not a quality measure.** Size says nothing about whether a model produces a *valid* document.
- **What is not measured yet:** first-try validity and repair rate for real models. The harness exists (\`genui-eval\`, see [Using with LLMs](/agents)) but this site publishes no model numbers because none have been run yet. Run it yourself:

\`\`\`bash
ANTHROPIC_API_KEY=… genui-eval --provider anthropic --model <id> --out report.json
\`\`\`

The numbers above are regenerated on every docs build from \`packages/tooling/eval\`.
`);

// ---- assets ----------------------------------------------------------------
const assets = join(root, "docs/assets");
const out = join(root, "apps/docs/public/assets");
mkdirSync(out, { recursive: true });
for (const f of readdirSync(assets)) copyFileSync(join(assets, f), join(out, f));

console.log("docs: generated protocol, components, schemas, benchmark; copied assets");
